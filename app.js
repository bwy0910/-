let mode = 'word';
let itemIndex = 0;
let startedAt = null;
let timerId = null;
let errors = 0;
let totalTyped = 0;
let soundOn = false;
let isComposing = false;
let itemReadyToAdvance = false;
let sessionComplete = false;
let selectedPassage = 0;
const passagePageSize = 90;
let sessionWords = [...content.word.items];
let sessionSentences = [...content.sentence.items];
const stats = { best: Number(localStorage.getItem('ongle-best') || 0), minutes: Number(localStorage.getItem('ongle-minutes') || 0) };

const $ = (id) => document.getElementById(id);
const prompt = $('prompt');
const input = $('typing-input');

function getPassagePages() {
  const source = content.passage.items[selectedPassage];
  const pages = [];
  let remaining = source.trim();
  while (remaining.length > passagePageSize) {
    let breakAt = remaining.lastIndexOf(' ', passagePageSize);
    const sentenceBreak = Math.max(remaining.lastIndexOf('.', passagePageSize), remaining.lastIndexOf('!', passagePageSize), remaining.lastIndexOf('?', passagePageSize));
    if (sentenceBreak > passagePageSize * 0.55) breakAt = sentenceBreak + 1;
    if (breakAt < 1) breakAt = passagePageSize;
    pages.push(remaining.slice(0, breakAt).trim());
    remaining = remaining.slice(breakAt).trim();
  }
  if (remaining) pages.push(remaining);
  return pages;
}

function shuffleWords() {
  sessionWords = [...content.word.items];
  for (let index = sessionWords.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [sessionWords[index], sessionWords[randomIndex]] = [sessionWords[randomIndex], sessionWords[index]];
  }
  sessionWords = sessionWords.slice(0, 15);
}

function shuffleSentences() {
  sessionSentences = [...content.sentence.items];
  for (let index = sessionSentences.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1));
    [sessionSentences[index], sessionSentences[randomIndex]] = [sessionSentences[randomIndex], sessionSentences[index]];
  }
  sessionSentences = sessionSentences.slice(0, 10);
}

function getCurrentItems() {
  if (mode === 'passage') return getPassagePages();
  if (mode === 'word') return sessionWords;
  if (mode === 'sentence') return sessionSentences;
  return content[mode].items;
}
function getCurrentTotal() { return getCurrentItems().length; }
function currentText() { return getCurrentItems()[itemIndex % getCurrentTotal()]; }

function renderPassagePicker() {
  const picker = $('passage-picker');
  picker.hidden = mode !== 'passage';
  if (mode !== 'passage') return;
  $('passage-select').innerHTML = content.passage.titles.map((title, index) => `<option value="${index}">${title}</option>`).join('');
  $('passage-select').value = String(selectedPassage);
}

function renderPrompt() {
  const text = currentText();
  const typed = input.value;
  prompt.innerHTML = [...text].map((char, index) => {
    const className = index < typed.length ? (typed[index] === char ? 'typed' : 'current') : (index === typed.length ? 'current' : 'pending');
    return `<span class="${className}">${char === ' ' ? '&nbsp;' : char}</span>`;
  }).join('');
}

function updateStats() {
  const elapsed = startedAt ? Math.max((Date.now() - startedAt) / 60000, 1 / 60) : 0;
  const wpm = elapsed ? Math.round((totalTyped / elapsed) / 5) : 0;
  const accuracy = totalTyped ? Math.max(0, Math.round(((totalTyped - errors) / totalTyped) * 100)) : 100;
  $('wpm').textContent = wpm;
  $('accuracy').textContent = accuracy;
  $('best').textContent = Math.max(stats.best, wpm);
  $('error-count').textContent = `오타 ${errors}`;
}

function updateTimer() {
  if (!startedAt) return;
  const seconds = Math.floor((Date.now() - startedAt) / 1000);
  $('timer').textContent = `${String(Math.floor(seconds / 60)).padStart(2, '0')}:${String(seconds % 60).padStart(2, '0')}`;
  updateStats();
}

function resetSession() {
  clearInterval(timerId);
  startedAt = null;
  timerId = null;
  itemIndex = 0;
  errors = 0;
  totalTyped = 0;
  itemReadyToAdvance = false;
  sessionComplete = false;
  if (mode === 'word') shuffleWords();
  if (mode === 'sentence') shuffleSentences();
  input.value = '';
  input.readOnly = false;
  input.classList.remove('ready');
  $('typing-card').classList.remove('ready');
  $('typing-card').hidden = false;
  $('completion-view').hidden = true;
  document.querySelector('.hint').textContent = '⌘ 시작하려면 입력창을 클릭하세요';
  $('timer').textContent = '00:00';
  $('session-progress').style.width = '10%';
  $('item-count').textContent = `01 / ${getCurrentTotal()}`;
  $('progress-label').textContent = content[mode].label;
  $('session-progress').style.width = `${Math.min(100 / getCurrentTotal(), 100)}%`;
  updateStats();
  renderPrompt();
}

function selectMode(nextMode) {
  mode = nextMode;
  document.body.classList.toggle('passage-mode', mode === 'passage');
  document.querySelectorAll('.mode-button').forEach((button) => button.classList.toggle('active', button.dataset.mode === mode));
  const current = content[mode];
  $('mode-kicker').textContent = current.kicker;
  $('practice-title').innerHTML = `${mode === 'passage' ? '고른 장문을 페이지별로 연습해 보세요' : current.title}<span>.</span>`;
  $('progress-label').textContent = current.label;
  $('level-label').textContent = current.level;
  renderPassagePicker();
  resetSession();
}

function completeItem() {
  const current = content[mode];
  const total = getCurrentTotal();
  const elapsed = startedAt ? Math.max((Date.now() - startedAt) / 60000, 1 / 60) : 1;
  const wpm = Math.round((totalTyped / elapsed) / 5);
  if (wpm > stats.best) { stats.best = wpm; localStorage.setItem('ongle-best', String(wpm)); }
  if (soundOn) { try { new AudioContext().close(); } catch (_) {} }
  itemIndex += 1;
  itemReadyToAdvance = false;
  if (itemIndex >= total) {
    sessionComplete = true;
    input.value = '';
    input.readOnly = true;
    $('session-progress').style.width = '100%';
    $('item-count').textContent = `${total} / ${total}`;
    $('progress-label').textContent = '한 세트 완료!';
    $('completion-copy').textContent = `${total}개 항목을 모두 연습했습니다.`;
    $('typing-card').hidden = true;
    $('completion-view').hidden = false;
    return;
  }
  input.value = '';
  input.readOnly = false;
  input.classList.remove('ready');
  $('typing-card').classList.remove('ready');
  document.querySelector('.hint').textContent = '⌘ 시작하려면 입력창을 클릭하세요';
  $('session-progress').style.width = `${Math.min(((itemIndex + 1) / total) * 100, 100)}%`;
  $('item-count').textContent = `${String(Math.min(itemIndex + 1, total)).padStart(2, '0')} / ${total}`;
  $('progress-label').textContent = itemIndex >= total ? '한 세트 완료!' : (mode === 'passage' ? '다음 페이지를 준비하세요' : current.label);
  errors = 0;
  renderPrompt();
  updateStats();
}

function handleTyping() {
  if (!startedAt) { startedAt = Date.now(); timerId = setInterval(updateTimer, 1000); }
  const text = currentText();
  const typed = input.value;
  totalTyped = Math.max(totalTyped, typed.length);
  errors = [...typed].reduce((count, char, index) => count + (char !== text[index] ? 1 : 0), 0);
  renderPrompt();
  updateStats();
  if (typed === text) {
    itemReadyToAdvance = true;
    input.readOnly = true;
    input.classList.add('ready');
    $('typing-card').classList.add('ready');
    document.querySelector('.hint').textContent = '↵ Enter를 눌러 다음으로';
  }
}

input.addEventListener('compositionstart', () => { isComposing = true; });
input.addEventListener('compositionend', () => {
  isComposing = false;
  handleTyping();
});
input.addEventListener('input', () => {
  if (!isComposing) handleTyping();
});
input.addEventListener('keydown', (event) => {
  if (event.key !== 'Enter') return;
  event.preventDefault();
  if (itemReadyToAdvance) completeItem();
});

document.querySelectorAll('.mode-button').forEach((button) => button.addEventListener('click', () => selectMode(button.dataset.mode)));
$('passage-select').addEventListener('change', (event) => {
  selectedPassage = Number(event.target.value);
  resetSession();
});
$('reset-button').addEventListener('click', resetSession);
$('completion-restart').addEventListener('click', resetSession);
$('sound-toggle').addEventListener('click', () => { soundOn = !soundOn; $('sound-toggle').textContent = soundOn ? '◗' : '◖'; $('sound-toggle').setAttribute('aria-label', soundOn ? '효과음 끄기' : '효과음 켜기'); });
document.addEventListener('keydown', (event) => { if (event.key === 'Escape') resetSession(); });

shuffleWords();
shuffleSentences();
renderPassagePicker();
renderPrompt();
updateStats();
